// Pure step-log parsing (no React) so it can be unit-tested with `node --test`.

export type StepInteractionOption = {
  id: string
  label: string
  description?: string
  danger?: boolean
  payload: Record<string, unknown>
}

export type StepInteraction = {
  provider?: string
  interactionId?: string
  cascadeId: string
  trajectoryId?: string
  stepIndex: number
  kind: string
  title: string
  target?: string
  reason?: string
  fallbackOnly?: boolean
  allowCustom?: boolean
  options: StepInteractionOption[]
}

export type StepBlock = {
  id: string
  kind: 'tool' | 'cmd' | 'thought' | 'file' | 'info'
  title: string
  /** 'stopped' is UI-only: a step that never finished because the message was stopped/interrupted. */
  status: 'running' | 'waiting' | 'done' | 'error' | 'stopped'
  detail?: string
  interaction?: StepInteraction | null
  /** Character offset in message body when this step first appeared (used for interleaved timeline). */
  offset?: number
  /** Local image path viewed or generated by this step (rendered as a thumbnail gallery). */
  imagePath?: string
}

export type TimelineSegment =
  | { type: 'text'; key: string; content: string }
  | { type: 'steps'; key: string; steps: StepBlock[] }

export type ParsedStepsResult = {
  steps: StepBlock[]
  metaTags: string[]
  /** Detail of the "上下文" meta step (which messages were carried this turn), if any. */
  contextDetail: string
}

export function formatDuration(ms: number): string {
  if (!ms || ms < 0) return '0s'
  const s = ms / 1000
  if (s < 60) return s.toFixed(1) + 's'
  const m = Math.floor(s / 60)
  const rem = Math.round(s % 60)
  return `${m}m ${rem}s`
}

// keep in sync with the meta list in desktop/store.mjs record() (meta steps get no body offset)
const META_PREFIXES = ['模型 · ', '请求思考强度 · ', '思考强度 · ', '上下文 · ', '提供商 · ', '渠道 · ']

function isMetaStep(step: StepBlock): boolean {
  return META_PREFIXES.some(p => step.title.startsWith(p))
}

function formatMetaTag(title: string): string {
  if (title.startsWith('模型 · ')) return title.slice(5).trim()
  if (title.startsWith('请求思考强度 · ')) return title.slice(9).trim()
  if (title.startsWith('思考强度 · ')) return title.slice(7).trim()
  if (title.startsWith('上下文 · ')) return title.replace('上下文 · ', '上下文 ').trim()
  if (title.startsWith('提供商 · ')) return title.slice(6).trim()
  if (title.startsWith('渠道 · ')) return title.slice(5).trim()
  return title.trim()
}

function isEmptyThought(step: StepBlock): boolean {
  if (step.kind !== 'thought') return false
  if (step.status === 'running' || step.status === 'waiting') return false
  return !step.detail?.trim()
}

function isTruncatedLogFragment(trimmed: string): boolean {
  // Legacy `substr(log, -524288)` could cut mid-line inside a ::step:: JSON or base64 payload,
  // leaving a raw base64/JSON tail as the first line.
  if (trimmed.length >= 48 && /^[A-Za-z0-9+/=_-]+$/.test(trimmed)) return true
  if (/"(?:status|detail|offset|title|kind)"\s*:/.test(trimmed) && !trimmed.startsWith('{')) return true
  return false
}

/** How unfinished (running / waiting) steps should be shown once the message has ended. */
export type StepEndState = 'done' | 'error' | 'stopped'

export function parseStepsWithMeta(log: string, messageEnded: boolean, endState: StepEndState = 'done'): ParsedStepsResult {
  if (!log) return { steps: [], metaTags: [], contextDetail: '' }
  const map = new Map<string, StepBlock>()
  const order: string[] = []
  let rawIdx = 0

  const upsert = (step: StepBlock) => {
    const existing = map.get(step.id)
    if (existing) {
      map.set(step.id, {
        ...existing,
        ...step,
        detail: step.detail ?? existing.detail,
        interaction: step.interaction !== undefined ? step.interaction : (step.status === 'waiting' ? existing.interaction : null),
        offset: existing.offset ?? step.offset,
        imagePath: step.imagePath ?? existing.imagePath
      })
    } else {
      map.set(step.id, step)
      order.push(step.id)
    }
  }

  for (const line of log.split('\n')) {
    const trimmed = line.trim()
    if (!trimmed) continue
    if (trimmed.startsWith('::step::')) {
      try {
        const parsed = JSON.parse(trimmed.slice(8)) as StepBlock
        if (parsed && parsed.id) {
          upsert({
            id: parsed.id,
            kind: parsed.kind || 'tool',
            title: parsed.title || '步骤',
            status: parsed.status || 'done',
            detail: parsed.detail,
            interaction: parsed.interaction,
            offset: typeof parsed.offset === 'number' ? parsed.offset : undefined,
            imagePath: typeof parsed.imagePath === 'string' && parsed.imagePath.trim() ? parsed.imagePath.trim() : undefined
          })
          continue
        }
      } catch {}
    }

    const legacyTool = trimmed.match(/^(.+?)\s·\s(pending|in_progress|completed|failed|cancelled)$/i)
    if (legacyTool) {
      const title = legacyTool[1].trim()
      const rawSt = legacyTool[2].toLowerCase()
      const status: StepBlock['status'] = rawSt === 'completed' ? 'done' : (rawSt === 'failed' || rawSt === 'cancelled') ? 'error' : 'running'
      upsert({ id: 'legacy:' + title, kind: 'cmd', title, status })
      continue
    }

    if (META_PREFIXES.some(p => trimmed.startsWith(p))) {
      upsert({ id: 'meta:' + trimmed.split(' · ')[0], kind: 'info', title: trimmed, status: 'done' })
      continue
    }

    if (order.length === 0 && isTruncatedLogFragment(trimmed)) continue

    const prevId = order[order.length - 1]
    const prev = prevId ? map.get(prevId) : undefined
    if (prev && prev.id.startsWith('raw:')) {
      prev.detail = ((prev.detail ? prev.detail + '\n' : '') + line).slice(-1200)
    } else {
      const id = 'raw:' + (rawIdx++)
      upsert({ id, kind: 'cmd', title: trimmed.slice(0, 80), status: 'done', detail: trimmed.length > 80 ? trimmed : undefined })
    }
  }

  const metaTags: string[] = []
  const steps: StepBlock[] = []
  let contextDetail = ''
  let contextTag = ''

  for (const id of order) {
    const raw = map.get(id)!
    const item: StepBlock = (messageEnded && (raw.status === 'running' || raw.status === 'waiting'))
      ? { ...raw, status: endState, interaction: null }
      : raw

    if (isMetaStep(item)) {
      const tag = formatMetaTag(item.title)
      if (item.title.startsWith('上下文 · ')) {
        contextTag = tag
        if (item.detail?.trim()) contextDetail = item.detail
      } else if (tag && !metaTags.includes(tag)) metaTags.push(tag)
      continue
    }

    if (isEmptyThought(item)) continue

    steps.push(item)
  }

  // model / effort first, the (longer) context summary last so truncation eats it, not the model
  if (contextTag) metaTags.push(contextTag)
  return { steps, metaTags, contextDetail }
}

/**
 * Interleave message body text and steps in chronological order using per-step body offsets.
 * Returns null for legacy messages that have no recorded offsets so callers can fall back cleanly.
 */
const FENCE_LINE_RE = /^ {0,3}(?:```|~~~)/gm
const NEXT_FENCE_LINE_RE = /(?:^|\n) {0,3}(?:```|~~~)[^\n]*(?:\n|$)/

/**
 * Never split inside a fenced code block: if `pos` falls inside an open fence, move it past the
 * closing fence line (or to the end when the fence is still streaming), so each segment stays
 * valid Markdown on its own.
 */
export function fenceSafeCut(text: string, pos: number): number {
  const opened = (text.slice(0, pos).match(FENCE_LINE_RE) || []).length
  if (opened % 2 === 0) return pos
  const m = text.slice(pos).match(NEXT_FENCE_LINE_RE)
  return m && m.index !== undefined ? pos + m.index + m[0].length : text.length
}

/** Drop surrounding blank lines but keep the first line's indentation (indented code, list continuations). */
function cleanSegment(raw: string): string {
  return raw.replace(/^(?:[ \t]*\n)+/, '').trimEnd()
}

export function buildTimelineSegments(body: string, steps: StepBlock[]): TimelineSegment[] | null {
  if (!steps.length || !steps.some(s => typeof s.offset === 'number')) return null
  const text = body || ''
  const segments: TimelineSegment[] = []
  let cursor = 0
  let textSeq = 0
  let groupSeq = 0

  for (const step of steps) {
    const rawOffset = typeof step.offset === 'number' ? step.offset : cursor
    const clamped = fenceSafeCut(text, Math.max(cursor, Math.min(text.length, rawOffset)))
    if (clamped > cursor) {
      const slice = cleanSegment(text.slice(cursor, clamped))
      if (slice) {
        segments.push({ type: 'text', key: `text-${textSeq++}`, content: slice })
      }
      cursor = clamped
    }
    const prev = segments[segments.length - 1]
    if (prev && prev.type === 'steps') {
      prev.steps.push(step)
    } else {
      segments.push({ type: 'steps', key: `steps-${groupSeq++}`, steps: [step] })
    }
  }

  if (cursor < text.length) {
    const tail = cleanSegment(text.slice(cursor))
    if (tail) {
      segments.push({ type: 'text', key: `text-${textSeq++}`, content: tail })
    }
  }

  return segments
}

// `\b` is ASCII-only, so it never matched after Chinese keywords; use a lookahead instead
const READ_STEP_RE = /^(?:read|glob|grep|view|search|list|find|ls|cat|读取|查看|搜索|检索)(?![A-Za-z0-9_])/i
const EDIT_STEP_RE = /^(?:write|edit|multiedit|replace|patch|apply_patch|写入|编辑|修改|创建)(?![A-Za-z0-9_])/i
const CMD_STEP_RE = /^(?:bash|shell|terminal|exec|run|pwsh|command|运行|执行)(?![A-Za-z0-9_])/i

export function summarizeStepGroup(steps: StepBlock[], active = false): string {
  if (!steps.length) return ''
  if (steps.length === 1) return steps[0].title

  let thoughts = 0
  let reads = 0
  let edits = 0
  let cmds = 0
  let others = 0

  for (const s of steps) {
    const t = (s.title || '').trim()
    if (s.kind === 'thought') thoughts++
    else if (s.kind === 'cmd' || CMD_STEP_RE.test(t)) cmds++
    else if (EDIT_STEP_RE.test(t)) edits++
    else if (s.kind === 'file' || READ_STEP_RE.test(t)) reads++
    else others++
  }

  const parts: string[] = []
  if (thoughts) parts.push(thoughts > 1 ? `思考 ${thoughts} 次` : '思考')
  if (reads) parts.push(`读取/搜索 ${reads} 次`)
  if (edits) parts.push(`修改 ${edits} 个文件`)
  if (cmds) parts.push(`运行 ${cmds} 条命令`)
  if (others) parts.push(`调用工具 ${others} 次`)

  const hasWaiting = steps.some(s => s.status === 'waiting')
  const hasRunning = active && steps.some(s => s.status === 'running')
  const prefix = hasWaiting ? '等待确认 · ' : hasRunning ? '执行中 · ' : '已'
  if (parts.length === 0) return `${prefix}执行 ${steps.length} 步`
  if (prefix === '已') return `已${parts.join('，')}`
  return `${prefix}${parts.join('，')}`
}

const IMAGE_EXT_RE = /\.(?:png|jpe?g|webp|gif|svg|bmp)$/i
const VIEW_IMAGE_TITLE_RE = /^(?:\[子代理\]\s*)?(?:read|view_file|view_image|image_view|查看图像|生成图像|读取|查看)\s*·\s*(.+)$/i
const DETAIL_IMG_PATH_RE = /"(?:file_path|path|image_path|imagePath|savedPath|outputPath|target_file)"\s*:\s*"([^"]+\.(?:png|jpe?g|webp|gif|svg|bmp))"/i

export function extractStepImagePath(step: StepBlock): string | null {
  if (step.imagePath && IMAGE_EXT_RE.test(step.imagePath)) return step.imagePath
  if (step.detail) {
    const m = step.detail.match(DETAIL_IMG_PATH_RE)
    if (m?.[1]) return m[1]
  }
  const tm = (step.title || '').trim().match(VIEW_IMAGE_TITLE_RE)
  if (tm?.[1]) {
    const candidate = tm[1].trim()
    if (!candidate.endsWith('…') && IMAGE_EXT_RE.test(candidate)) return candidate
  }
  return null
}

export function extractStepImages(steps: StepBlock[]): Array<{ path: string; name: string }> {
  const seen = new Set<string>()
  const out: Array<{ path: string; name: string }> = []
  for (const s of steps) {
    const p = extractStepImagePath(s)
    if (!p || seen.has(p)) continue
    seen.add(p)
    const name = p.split(/[/\\]/).pop() || p
    out.push({ path: p, name })
  }
  return out
}
